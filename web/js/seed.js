// ---------------------------------------------------------------------------
function makeEvent(e) {
  const upvotes = e.upvotes ?? 0;
  const downvotes = e.downvotes ?? 0;
  return {
    title: e.title,
    description: e.description,
    eventType: e.eventType,
    tags: e.tags || [],
    hostId: e.hostId ?? null,
    hostName: e.hostName,
    coverImageUrl: null,
    images: [],
    startAt: e.startAt,
    endAt: e.endAt ?? plusHours(e.startAt, 4),
    venueName: e.venueName ?? null,
    neighborhood: e.neighborhood,
    approxArea: e.approxArea,
    exactAddress: e.exactAddress ?? null,
    priceCents: e.priceCents ?? 0,
    capacity: e.capacity ?? null,
    ageMin: e.ageMin ?? 14,
    ageMax: e.ageMax ?? 18,
    recommendedFor: e.recommendedFor || [],
    committedCount: e.committedCount ?? 0,
    interestedCount: e.interestedCount ?? 0,
    upvotes,
    downvotes,
    voteScore: upvotes - downvotes,
    status: e.status ?? 'published',
    isFeatured: e.isFeatured ?? false,
    createdBy: e.createdBy ?? 'admin',
    // id is attached below so each event is self-contained.
    id: e.id,
  };
}


const NOW = new Date();

// Build a startAt N days from now, at a given local hour:minute. Returns ISO-8601.
function inDays(days, hour = 19, minute = 0) {
  const d = new Date(NOW.getTime());
  d.setDate(d.getDate() + days);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}
// endAt = startAt + hours.
function plusHours(isoStart, hours) {
  return new Date(new Date(isoStart).getTime() + hours * 60 * 60 * 1000).toISOString();
}

